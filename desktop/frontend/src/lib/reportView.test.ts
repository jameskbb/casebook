import { describe, expect, it } from 'vitest'
import { parseReportHtml } from './reportView'

describe('parseReportHtml', () => {
  it('turns the report HTML into preview nodes without marks', () => {
    const nodes = parseReportHtml('<h1>INV-0001: T</h1>\n<h2>Question</h2>\n<p>Why?</p>\n<ul><li><strong>C-001</strong> A claim<ul><li>Why: so</li></ul></li></ul>\n')
    expect(nodes).not.toBeNull()
    expect(nodes?.filter((n) => n.type === 'el').map((n) => (n.type === 'el' ? n.tag : ''))).toEqual(['h1', 'h2', 'p', 'ul'])
  })
  it('keeps escaped text as text', () => {
    const nodes = parseReportHtml('<p>1 &lt; 2 &amp; &lt;b&gt;x&lt;/b&gt;</p>')
    const p = nodes?.[0]
    expect(p?.type === 'el' && p.children[0]?.type === 'text' ? p.children[0].text : '').toBe('1 < 2 & <b>x</b>')
  })
  it('keeps the day headings and the closing emphasis line', () => {
    const nodes = parseReportHtml('<h3>12 October 2026</h3>\n<p><em>Generated by Casebook</em></p>\n')
    expect(nodes?.filter((n) => n.type === 'el').map((n) => (n.type === 'el' ? n.tag : ''))).toEqual(['h3', 'p'])
    const p = nodes?.find((n) => n.type === 'el' && n.tag === 'p')
    expect(p?.type === 'el' && p.children[0]?.type === 'el' ? p.children[0].tag : '').toBe('em')
  })
})
