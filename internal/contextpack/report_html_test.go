func TestReportHTMLEscapesStoredText(t *testing.T) {
	md := "# INV-0001: A <b>bold</b> & \"quoted\" title\n\n## Question\n\nIs 1 < 2 & 3 > 2?\n\n## Current claims\n\n- **C-001** Text with <script>alert(1)</script> inside. (High confidence, Human verified)\n  - Why: because & so.\n"
	html := contextpack.ReportHTML(md)
	for _, bad := range []string{"<b>", "<script>", "&\"", "& so"} {
		if strings.Contains(html, bad) {
			t.Fatalf("unescaped %q in %s", bad, html)
		}
	}
	for _, want := range []string{
		"<h1>INV-0001: A &lt;b&gt;bold&lt;/b&gt; &amp; &#34;quoted&#34; title</h1>",
		"<h2>Question</h2>",
		"<p>Is 1 &lt; 2 &amp; 3 &gt; 2?</p>",
		"<li><strong>C-001</strong> Text with &lt;script&gt;alert(1)&lt;/script&gt; inside. (High confidence, Human verified)<ul><li>Why: because &amp; so.</li></ul></li>",
	} {
		if !strings.Contains(html, want) {
			t.Fatalf("missing %q in %s", want, html)
		}
	}
}

func TestReportHTMLDayHeadingsAndFooter(t *testing.T) {
	md := "## Timeline (UTC)\n\n### 2026-10-05\n\n- 11:13 ai claude-code: Created <x>\n\n### 2026-10-06 & later\n\n_Generated by Casebook from INV-0002 <b>._\n"
	html := contextpack.ReportHTML(md)
	for _, want := range []string{
		"<h3>2026-10-05</h3>\n<ul><li>11:13 ai claude-code: Created &lt;x&gt;</li></ul>\n",
		"<h3>2026-10-06 &amp; later</h3>",
		"<p><em>Generated by Casebook from INV-0002 &lt;b&gt;.</em></p>",
	} {
		if !strings.Contains(html, want) {
			t.Fatalf("missing %q in %s", want, html)
		}
	}
	if strings.Contains(html, "###") || strings.Contains(html, "<p>_") {
		t.Fatalf("raw Markdown left in %s", html)
	}
}

func TestReportHTMLDropsBlockMarkerEscapes(t *testing.T) {
	for in, want := range map[string]string{
		`\# not a heading`: "<p># not a heading</p>",
		`\- not a bullet`:  "<p>- not a bullet</p>",
		`\* star & <i>`:    "<p>* star &amp; &lt;i&gt;</p>",
		`\_ underscore_`:   "<p>_ underscore_</p>",
		`12\. not a list`:  "<p>12. not a list</p>",
		`3\) not a list`:   "<p>3) not a list</p>",
		`a \# inside`:      `<p>a \# inside</p>`,
		`\q not a marker`:  `<p>\q not a marker</p>`,
	} {
		if got := contextpack.ReportHTML(in + "\n"); got != want+"\n" {
			t.Errorf("ReportHTML(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestReportHTMLStoredTextThatLooksLikeMarkdown(t *testing.T) {
	a := apptest.Open(t)
	ctx := context.Background()
	inv, err := a.CreateInvestigation(ctx, apptest.Human, app.CreateInvestigationInput{Title: "# Hash title", ProblemStatement: "# Not a heading <b>"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := a.UpdateConclusion(ctx, apptest.Human, inv.Ref, app.ConclusionInput{Conclusion: "- not a bullet"}); err != nil {
		t.Fatal(err)
	}
	md, err := a.Report(ctx, inv.Ref, app.ReportOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(md, `\# Not a heading`) || !strings.Contains(md, `\- not a bullet`) {
		t.Fatalf("report no longer escapes block markers; update this test: %s", md)
	}
	html := contextpack.ReportHTML(md)
	for _, want := range []string{
		"<h1>INV-0001: # Hash title</h1>",
		"<p># Not a heading &lt;b&gt;</p>",
		"<p>- not a bullet</p>",
		"<p><em>Generated by Casebook from INV-0001.</em></p>",
	} {
		if !strings.Contains(html, want) {
			t.Fatalf("missing %q in %s", want, html)
		}
	}
	if strings.Contains(html, `\`) {
		t.Fatalf("backslash left in %s", html)
	}
}

